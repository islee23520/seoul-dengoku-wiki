// 상세 행(여덞 키) → CK3. 값은 이동만 하고 합성하지 않는다.
export function convertDetailAbilities(personId, jsonText, jsonKoText) {
  const je = JSON.parse(jsonText); const jk = JSON.parse(jsonKoText);
  const profE = je.characterProfile; const profK = jk.characterProfile;
  if (!profE?.abilities || !profK?.abilities) throw Object.assign(new Error(`E_ABILITY_KEYS: ${personId} abilities 없음`), { code: EXIT.ABILITY_KEYS });
  if (JSON.stringify(profE.abilities) !== JSON.stringify(profK.abilities)) {
    throw Object.assign(new Error(`E_JSON_KO_MISMATCH: ${personId}`), { code: EXIT.JSON_KO_MISMATCH });
  }
  const oldKeys = Object.keys(profE.abilities);
  if (oldKeys.join(',') !== OLD_KEYS.join(',')) {
    throw Object.assign(new Error(`E_ABILITY_KEYS: ${personId} 키 집합 = ${oldKeys.join(',')}`), { code: EXIT.ABILITY_KEYS });
  }
  const old = {}; const next = {};
  for (const k of OLD_KEYS) old[k] = { base: profE.abilities[k].base, effective: profE.abilities[k].effective };
  for (const k of CK3_KEYS) {
    const from = Object.keys(OLD_TO_CK3).find((o) => OLD_TO_CK3[o] === k);
    next[k] = { base: old[from].base, effective: old[from].effective };
  }
  profE.abilities = Object.fromEntries(CK3_KEYS.map((k) => [k, { ...next[k] }]));
  profK.abilities = Object.fromEntries(CK3_KEYS.map((k) => [k, { ...next[k] }]));
  const remappedEffects = [];
  for (const p of [profE, profK]) {
    for (const t of p.traits ?? []) for (const e of t.effects ?? []) {
      if (e.ability in OLD_TO_CK3 && OLD_TO_CK3[e.ability]) {
        remappedEffects.push(`${personId}:${t.id}:${e.ability}->${OLD_TO_CK3[e.ability]}:${e.delta}`);
        e.ability = OLD_TO_CK3[e.ability];
      }
    }
  }
  for (const p of [profE, profK]) {
    const deltas = effectDeltas(p);
    for (const k of CK3_KEYS) {
      checkStat(personId, k, p.abilities[k].base, p.abilities[k].effective);
      if (p.abilities[k].effective !== clamp(p.abilities[k].base + (deltas[k] ?? 0), 0, 100)) {
        throw Object.assign(new Error(`E_EFFECT_TOTAL: ${personId}:${k}`), { code: EXIT.EFFECT_TOTAL });
      }
    }
  }
  return { json: JSON.stringify(je), jsonKo: JSON.stringify(jk), old, remappedEffects };
}

// 이미 CK3인 상세 행 검증(멱등 재실행 경로).
export function verifyDetailAbilities(personId, jsonText, jsonKoText) {
  const je = JSON.parse(jsonText); const jk = JSON.parse(jsonKoText);
  if (JSON.stringify(je.characterProfile?.abilities) !== JSON.stringify(jk.characterProfile?.abilities)) {
    throw Object.assign(new Error(`E_JSON_KO_MISMATCH: ${personId}`), { code: EXIT.JSON_KO_MISMATCH });
  }
  const keys = Object.keys(je.characterProfile?.abilities ?? {});
  if (keys.join(',') !== CK3_KEYS.join(',')) {
    throw Object.assign(new Error(`E_ABILITY_KEYS: ${personId} 키 집합 = ${keys.join(',')}`), { code: EXIT.ABILITY_KEYS });
  }
  const deltas = effectDeltas(je.characterProfile);
  for (const k of CK3_KEYS) {
    checkStat(personId, k, je.characterProfile.abilities[k].base, je.characterProfile.abilities[k].effective);
    if (je.characterProfile.abilities[k].effective !== clamp(je.characterProfile.abilities[k].base + (deltas[k] ?? 0), 0, 100)) {
      throw Object.assign(new Error(`E_EFFECT_TOTAL: ${personId}:${k}`), { code: EXIT.EFFECT_TOTAL });
    }
  }
}

// 직업 등급 × 품계 보정 → 여섯 값.
export function deriveTableStats(personId, occupationKo, rankKo) {
  let cls = null;
  for (const [id, keywords] of OCCUPATION_CLASSES) if (keywords.some((k) => occupationKo.includes(k))) { cls = id; break; }
  if (!cls) throw Object.assign(new Error(`E_UNKNOWN_OCCUPATION: ${personId} "${occupationKo}"`), { code: EXIT.UNKNOWN_OCCUPATION });
  const mod = RANK_MODIFIER[rankKo];
  if (!mod) throw Object.assign(new Error(`E_UNKNOWN_RANK: ${personId} "${rankKo}"`), { code: EXIT.UNKNOWN_RANK });
  const stats = {};
  for (const k of CK3_KEYS) {
    const base = clamp(CLASS_BASE[cls][k] + (mod[k] ?? 0), 1, 20);
    stats[k] = { base, effective: base };
    checkStat(personId, k, base, base);
  }
  return { classId: cls, modifier: mod, stats };
}

// 파생 최소 행(050 열값 + 표만으로 구성). json=영문 열, json_ko=한국어 열.
