// ---- SQL 텍스트 파싱/직렬화 ---------------------------------------------------
// 행당 INSERT 1문 형식(export-sql.mjs 산출물)만 다룬다. 값: '문자열('' 이스케이프)' | 숫자 | NULL.
function parseValues(tail) {
  const vals = []; let cur = ''; let inStr = false; let isStr = false;
  for (let i = 0; i < tail.length; i++) {
    const c = tail[i];
    if (inStr) {
      if (c === "'") { if (tail[i + 1] === "'") { cur += "'"; i++; } else inStr = false; } else cur += c;
    } else if (c === "'") {
      if (!isStr && cur.trim() === '') cur = ''; // ', ' 구분자의 선행 공백은 값이 아니다
      inStr = true; isStr = true;
    }
    else if (c === ',') { vals.push(isStr ? cur : cur.trim()); cur = ''; isStr = false; }
    else cur += c;
  }
  vals.push(isStr ? cur : cur.trim());
  return vals;
}
export function parseInsertLine(line, table, columns) {
  const m = line.match(new RegExp(`^INSERT INTO ${table} \\(([^)]*)\\) VALUES \\((.*)\\);$`));
  if (!m) throw Object.assign(new Error(`E_INSERT_SHAPE: ${table} 형식 밖 행: ${line.slice(0, 90)}`), { code: EXIT.INSERT_SHAPE });
  const cols = m[1].split(',').map((c) => c.trim());
  if (cols.join(',') !== columns.join(',')) throw Object.assign(new Error(`E_INSERT_SHAPE: ${table} 열 순서 불일치`), { code: EXIT.INSERT_SHAPE });
  const vals = parseValues(m[2]);
  const row = {};
  cols.forEach((c, i) => { row[c] = vals[i] === 'NULL' ? null : vals[i]; });
  return row;
}
export const sqlString = (v) => (v === null ? 'NULL' : `'${String(v).replaceAll("'", "''")}'`);
export function insertLine(table, columns, row) {
  return `INSERT INTO ${table} (${columns.join(', ')}) VALUES (${columns.map((c) => sqlString(row[c])).join(', ')});`;
}

function splitStatements(text) {
  if (!text.startsWith('--')) throw Object.assign(new Error('E_HEADER: 머리말 주석 2줄로 시작하지 않는다'), { code: EXIT.HEADER });
  const nl = text.indexOf('\n'); const nl2 = text.indexOf('\n', nl + 1);
  const headerLines = [text.slice(0, nl), text.slice(nl + 1, nl2)];
  const rest = text.slice(nl2 + 1);
  const lines = rest.split('\n').filter((l) => l.length > 0);
  return { headerLines, lines };
}

// ---- 능력치 검증 --------------------------------------------------------------
const clamp = (v, lo, hi) => Math.max(lo, Math.min(hi, v));
function checkStat(id, key, base, effective) {
  if (!Number.isInteger(base) || base < 1 || base > 20 || !Number.isInteger(effective) || effective < 0 || effective > 100) {
    throw Object.assign(new Error(`E_RANGE: ${id}:${key} base=${base} effective=${effective}`), { code: EXIT.RANGE });
  }
}
function effectDeltas(profile) {
  const deltas = {};
  for (const t of profile.traits ?? []) for (const e of t.effects ?? []) {
    if (!(e.ability in OLD_TO_CK3) && !CK3_KEYS.includes(e.ability)) {
      throw Object.assign(new Error(`E_EFFECT_ABILITY: ${e.ability}`), { code: EXIT.EFFECT_ABILITY });
    }
    deltas[e.ability] = (deltas[e.ability] ?? 0) + e.delta;
  }
  return deltas;
}

