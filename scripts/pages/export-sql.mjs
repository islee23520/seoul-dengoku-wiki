function makeRenderer(X) {
  const inl = (nodes) => (nodes ?? []).map((n) => {
    if (n.kind === 'docLink') { const r = routeById.get(n.targetDocumentId); const t = X(n.text); return r ? `[${t}](${r})` : t; }
    return X(n.text ?? '');
  }).join('');
  const cell = (c) => (Array.isArray(c) ? inl(c) : X(String(c))).replaceAll('|', '\\|').replaceAll('\n', ' ');
  const block = (b) => {
    switch (b.kind) {
      case 'heading': return `${'#'.repeat(b.level ?? b.depth ?? 2)} ${b.inlines ? inl(b.inlines) : X(b.text?.ko ?? '')}`;
      case 'paragraph': return b.inlines ? inl(b.inlines) : X(b.text?.ko ?? '');
      case 'list': return (b.items ?? []).map((it, i) => `${b.ordered ? `${i + 1}.` : '-'} ${Array.isArray(it) ? inl(it) : X(it.ko ?? '')}`).join('\n');
      case 'table': {
        const head = `| ${(b.header ?? []).map(cell).join(' | ')} |`;
        const sep = `| ${(b.header ?? []).map(() => '---').join(' | ')} |`;
        return [head, sep, ...(b.rows ?? []).map((r) => `| ${r.map(cell).join(' | ')} |`)].join('\n');
      }
      case 'blockQuote': return (b.lines ?? []).map((l) => `> ${Array.isArray(l) ? inl(l) : X(l)}`).join('\n');
      case 'codeFence': return `${b.fence ?? '```'}${b.info ?? ''}\n${X(b.text ?? '')}\n${b.fence ?? '```'}`;
      case 'thematicBreak': return '---';
      default: throw new Error(`E_GDD_BLOCK_KIND:${b.kind}`);
    }
  };
  return block;
}
