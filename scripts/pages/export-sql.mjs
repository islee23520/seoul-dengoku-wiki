#!/usr/bin/env node
// Exports the PUBLIC wiki + GDD projections into raw SQL files (data/sql/*.sql), in English and Korean.
// Source of truth for GitHub Pages is data/sql; the site build never touches PostgreSQL.
//
//   PostgreSQL wiki --(npm run generate)--> src/generated/** --(this script)--> data/sql/*.sql
//
// Korean text is the original projection; English comes from the existing English articles and
// scripts/pages/i18n-ko-en.json. Only public projections are read (never wiki_private, never .omo).
// Every Korean string that needs English must have an entry in the cache; missing strings are
// written to scripts/pages/i18n-missing.json and the export fails.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const OUT = path.join(REPO, 'data/sql');
const CACHE_PATH = path.join(REPO, 'scripts/pages/i18n-ko-en.json');
const MISSING_PATH = path.join(REPO, 'scripts/pages/i18n-missing.json');
const HANGUL = /[\uAC00-\uD7A3]/;
const hasHangul = (s) => typeof s === 'string' && HANGUL.test(s);

const cache = fs.existsSync(CACHE_PATH) ? JSON.parse(fs.readFileSync(CACHE_PATH, 'utf8')) : {};
const missing = new Set();
const T = (s) => {
  if (!hasHangul(s)) return s;
  const v = cache[s];
  if (v === undefined) { missing.add(s); return s; }
  return v;
};
const TL = (md) => md.split('\n').map(T).join('\n');
const K = (s) => s;
const KL = (md) => md;

const gen = (p) => import(pathToFileURL(path.join(REPO, 'src/generated', p)).href);
const readJson = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));
const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
  const p = path.join(dir, e.name);
  return e.isDirectory() ? walk(p) : p.endsWith('.json') ? [p] : [];
}).sort();

const q = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replaceAll("'", "''")}'`);
const insert = (table, cols, rows) => rows.map((r) => `INSERT INTO ${table} (${cols.join(', ')}) VALUES (${cols.map((c) => q(r[c])).join(', ')});`).join('\n');
const writeSql = (name, header, body) => {
  fs.mkdirSync(OUT, { recursive: true });
  fs.writeFileSync(path.join(OUT, name), `-- ${header}\n-- Generated by scripts/pages/export-sql.mjs. Raw data: edit via the export, not by hand.\n\n${body}\n`);
};

// ---- world documents ----------------------------------------------------
function cleanWorldMarkdown(md, ko) {
  const out = [];
  for (const line of md.split('\n')) {
    const a = line.match(/^<a id="([^"]*)"><\/a>\s*$/);
    if (a) { if (ko || /^[\x20-\x7e]+$/.test(a[1])) out.push(line); continue; }
    out.push(line);
  }
  let text = out.join('\n');
  const fragOk = (f) => (f && (ko || /^#[\x20-\x7e]+$/.test(f)) ? f : '');
  text = text.replace(/\]\(\/(?:en\/)?world\/([A-Za-z0-9_-]*)(#[^)\s]*)?\)/g, (m, slug, frag = '') => `](/wiki/${slug ? `${slug}/` : ''}${fragOk(frag)})`);
  text = text.replace(/\[([^\]]+)\]\(https:\/\/github\.com\/islee23520\/seoul-dengoku\/[^)]*\)/g, '$1');
  text = text.replace(/\]\(\/(?:en\/)?(states|people|families|updates|categories)(\/[^)\s#]*)?(#[^)\s]*)?\)/g, (m, a, b = '', f = '') => `](/wiki/${a}${b}/${fragOk(f)})`);
  if (!ko) text = text.replace(/\]\(([^)\s]*)#[^)\s]*[\uAC00-\uD7A3][^)\s]*\)/g, ']($1)');
  return text;
}

const worldEnDir = path.join(REPO, 'src/generated/world-en');
const worldKoDir = path.join(REPO, 'src/generated/world');
const worldDocs = fs.readdirSync(worldEnDir).filter((f) => f.endsWith('.json')).sort().map((f) => {
  const en = readJson(path.join(worldEnDir, f));
  const ko = readJson(path.join(worldKoDir, f));
  return { slug: en.slug, title: T(en.title), title_ko: ko.title, body: TL(cleanWorldMarkdown(en.reviewText, false)), body_ko: cleanWorldMarkdown(ko.reviewText, true) };
});

// ---- categories ---------------------------------------------------------
const { categoryIndex } = await gen('categoryIndex.ts');
const wikiCategories = [];
const docCategory = new Map();
categoryIndex.categories.forEach((c, i) => {
  wikiCategories.push({ id: c.id, parent_id: null, sort: i, label: T(c.label), label_ko: c.label, summary: T(c.summary), summary_ko: c.summary });
  c.documents.forEach((d, j) => { if (d.slug !== 'index' && !docCategory.has(d.slug)) docCategory.set(d.slug, { id: c.id, sort: j }); });
  c.children.forEach((ch, k) => wikiCategories.push({ id: ch.id, parent_id: c.id, sort: k, label: T(ch.label), label_ko: ch.label, summary: T(ch.summary ?? ''), summary_ko: ch.summary ?? '' }));
});
wikiCategories.push({ id: 'other', parent_id: null, sort: 999, label: 'Other', label_ko: '기타', summary: 'Pages not yet filed under a category.', summary_ko: '아직 분류되지 않은 문서.' });
const wikiDocRows = worldDocs.map((d, i) => {
  const cat = docCategory.get(d.slug) ?? { id: 'other', sort: i };
  return { slug: d.slug, title: d.title, title_ko: d.title_ko, category_id: cat.id, sort: cat.sort, body_md: d.body, body_ko_md: d.body_ko };
});

// ---- factions, states, people, updates ---------------------------------
const { stateCatalog } = await gen('stateCatalog.ts');
const { politicalCatalog } = await gen('politicalCatalog.ts');
const canonicalState = new Map();
for (const line of readJson(path.join(worldEnDir, 'Sixteen-States.json')).reviewText.split('\n')) {
  const m = line.match(/^\|\s*(S(?:0[1-9]|1[0-6]))\s*\|\s*([^|]+?)\s*\|/);
  if (m && !canonicalState.has(m[1])) canonicalState.set(m[1], m[2]);
}
if (canonicalState.size !== stateCatalog.length) throw new Error(`E_STATE_NAMES: ${canonicalState.size} canonical names for ${stateCatalog.length} states`);
const stateEn = (id, ko) => canonicalState.get(id) ?? T(ko);

// Owner decision 2026-11-10 (issue 708): three factions. Display names live in this one table.
const FACTION_DEFS = [
  { id: 'government', hegemon: 'S06', name: 'The Government', name_ko: '정부' },
  { id: 'free-city', hegemon: 'S02', name: 'Free City', name_ko: '자유도시' },
  { id: 'arc', hegemon: null, kind: 'union', name: 'Arc', name_ko: 'Arc' },
];
const factionRows = FACTION_DEFS.map((d, i) => {
  const h = politicalCatalog.hegemons.find((x) => (d.hegemon ? x.stateId === d.hegemon : x.kind === d.kind));
  if (!h) throw new Error(`E_FACTION_SOURCE: no hegemon for ${d.id}`);
  return { id: d.id, sort: i, name: d.name, name_ko: d.name_ko, color: h.color, center_region: T(h.centerRegion), center_region_ko: h.centerRegion, ai_position: T(h.aiPosition), ai_position_ko: h.aiPosition, members: h.memberStateIds };
});
factionRows.push({ id: 'independent', sort: 3, name: 'Independent (affiliation undecided)', name_ko: '독립 (소속 미정)', color: '#697586', center_region: '', center_region_ko: '', ai_position: '', ai_position_ko: '', members: [] });
const factionOfState = new Map();
for (const f of factionRows) for (const id of f.members) factionOfState.set(id, f.id);
const factionOf = (stateId) => factionOfState.get(stateId) ?? 'independent';

const stateRows = stateCatalog.map((s, i) => ({
  slug: s.slug, id: s.id, sort: i, faction_id: factionOf(s.id),
  name: stateEn(s.id, s.name), name_ko: s.name, government: T(s.government), government_ko: s.government, power: T(s.power), power_ko: s.power,
  cause: T(s.cause), cause_ko: s.cause, ruler: T(s.ruler), ruler_ko: s.ruler, capital: T(s.capital), capital_ko: s.capital,
  base: T(s.currentBase?.name ?? ''), base_ko: s.currentBase?.name ?? '',
}));
const stateName = new Map(stateRows.map((s) => [s.id, s.name]));
const { peopleCatalog } = await gen('peopleCatalog.ts');
const personRows = peopleCatalog.map((p, i) => ({
  id: p.id, sort: i, faction_id: factionOf(p.state),
  name: T(p.name), name_ko: p.name, title: T(p.title), title_ko: p.title, position: T(p.position), position_ko: p.position,
  rank: T(p.rank), rank_ko: p.rank, tier: p.commonTier, occupation: T(p.occupation), occupation_ko: p.occupation,
  gender: T(p.gender), gender_ko: p.gender, stage: T(p.stage), stage_ko: p.stage,
  state_id: p.state, state_name: stateName.get(p.state) ?? T(p.stateName), state_name_ko: p.stateName,
}));
const { wikiUpdates } = await gen('wikiUpdates.ts');
const updateRows = wikiUpdates.map((u, i) => ({
  sort: i, date: u.date, category: T(u.category), category_ko: u.category, status: T(u.status), status_ko: u.status,
  title: T(u.title), title_ko: u.title, source: u.source, slug: (u.route.match(/^\/world\/([^/#]+)/) ?? [])[1] ?? null,
}));

// ---- GDD ----------------------------------------------------------------
const GDD_DIR = path.join(REPO, 'gdd/canon/locales/ko-KR');
const GDD_CATS = [
  ['design', 'Product Design', '제품 설계', 'root'], ['rules', 'Game Rules', '게임 규칙', 'rules'], ['architecture', 'Architecture', '아키텍처', 'architecture'],
  ['references', 'Reference Research', '레퍼런스 연구', 'references'], ['decisions', 'Decision Records', '결정 기록', 'adr'], ['art', 'Art Design', '아트 설계', 'art'],
  ['system-design', 'System Design', '시스템 설계', 'system-design'], ['proposals', 'Design Proposals', '설계 제안', 'proposals'],
];
const catOfFile = (rel) => {
  if (/^adr-\d+\.json$/.test(rel)) return 'decisions';
  const dir = rel.split('/')[0];
  return GDD_CATS.find((c) => c[3] === dir)?.[0] ?? 'design';
};
const gddMeta = walk(GDD_DIR).map((abs) => {
  const rel = path.relative(GDD_DIR, abs).replaceAll('\\', '/');
  const j = readJson(abs);
  return { j, rel, id: j.document?.id ?? j.id, slug: path.basename(rel, '.json'), category: catOfFile(rel) };
});
const routeById = new Map(gddMeta.map((m) => [m.id, `/gdd/${m.category}/${m.slug}/`]));

function makeRenderer(X) {
  const inl = (nodes) => (nodes ?? []).map((n) => {
    if (n.kind === 'docLink') { const r = routeById.get(n.targetDocumentId); const t = X(n.text); return r ? `[${t}](${r})` : t; }
    return X(n.text ?? '');
  }).join('');
  const cell = (c) => (Array.isArray(c) ? inl(c) : X(String(c))).replaceAll('|', '\\|').replaceAll('\n', ' ');
  const block = (b) => {
    switch (b.kind) {
      case 'heading': return `${'#'.repeat(b.level ?? b.depth ?? 2)} ${b.inlines ? inl(b.inlines) : X(b.text?.ko ?? '')}`;
      case 'paragraph': return b.inlines ? inl(b.inlines) : X(b.text?.ko ?? '');
      case 'list': return (b.items ?? []).map((it, i) => `${b.ordered ? `${i + 1}.` : '-'} ${Array.isArray(it) ? inl(it) : X(it.ko ?? '')}`).join('\n');
      case 'table': {
        const head = `| ${(b.header ?? []).map(cell).join(' | ')} |`;
        const sep = `| ${(b.header ?? []).map(() => '---').join(' | ')} |`;
        return [head, sep, ...(b.rows ?? []).map((r) => `| ${r.map(cell).join(' | ')} |`)].join('\n');
      }
      case 'blockQuote': return (b.lines ?? []).map((l) => `> ${Array.isArray(l) ? inl(l) : X(l)}`).join('\n');
      case 'codeFence': return `${b.fence ?? '```'}${b.info ?? ''}\n${X(b.text ?? '')}\n${b.fence ?? '```'}`;
      case 'thematicBreak': return '---';
      default: throw new Error(`E_GDD_BLOCK_KIND:${b.kind}`);
    }
  };
  return block;
}
const blockEn = makeRenderer(T);
const blockKo = makeRenderer(K);
const gddRows = gddMeta.map((m, i) => {
  const blocks = m.j.blocks ?? m.j.content;
  const first = blocks.find((b) => b.kind === 'heading');
  const titleKo = m.j.locales?.ko?.title ?? (first ? blockKo(first).replace(/^#+\s*/, '') : m.slug);
  const titleEn = m.j.locales?.ko?.title ? T(m.j.locales.ko.title) : (first ? blockEn(first).replace(/^#+\s*/, '') : m.slug);
  const sumKo = m.j.locales?.ko?.summary ?? '';
  return {
    id: m.id, category_id: m.category, slug: m.slug, title: titleEn, title_ko: titleKo, summary: sumKo ? T(sumKo) : '', summary_ko: sumKo,
    status: m.j.status ?? 'accepted', sort: i, source_path: m.j.source?.path ?? null,
    body_md: blocks.map(blockEn).join('\n\n'), body_ko_md: blocks.map(blockKo).join('\n\n'),
  };
});

// ---- link normalisation (locale neutral: /wiki/... and /gdd/...) --------
const routeBySource = new Map(gddRows.map((r) => [r.source_path?.toLowerCase(), `/gdd/${r.category_id}/${r.slug}/`]));
const gddRouteSet = new Map(gddRows.map((r) => [`/gdd/${r.category_id}/${r.slug}/`.toLowerCase(), `/gdd/${r.category_id}/${r.slug}/`]));
const wikiRouteSet = new Map(wikiDocRows.map((r) => [`/wiki/${r.slug}/`.toLowerCase(), `/wiki/${r.slug}/`]));
const fixSiteLinks = (md) => md.replace(/\]\((\/(?:gdd|wiki)\/[^)\s#]*?)\/?(#[^)\s]*)?\)/g, (m, p, frag = '') => {
  const key = `${p.replace('/wiki/world/', '/wiki/')}/`.toLowerCase();
  const hit = gddRouteSet.get(key) ?? wikiRouteSet.get(key);
  if (hit) return `](${hit}${frag})`;
  return /^\/wiki\/(states|people|updates)\//.test(p) || p === '/wiki' || p === '/gdd' ? m : ']()';
}).replace(/\[([^\]]*)\]\(\)/g, '$1');
const fixGddRelative = (md, sourcePath) => {
  const dir = path.posix.dirname(sourcePath ?? '.');
  return md.replace(/\[([^\]]*)\]\(([^)\s#]+\.md)(#[^)\s]*)?\)/gi, (m, label, href) => {
    if (/^[a-z][a-z0-9+.-]*:/i.test(href) || href.startsWith('/')) return m;
    const target = routeBySource.get(path.posix.normalize(path.posix.join(dir, href)).toLowerCase());
    return target ? `[${label}](${target})` : label;
  });
};
const fixWikiRoutes = (md) => md
  .replace(/\[([^\]]*)\]\((?![a-z][a-z0-9+.-]*:|\/|#)[^)\s]+\.md(?:#[^)\s]*)?\)/gi, '$1')
  .replace(/\]\(\/(people|states|families|updates)\/([^)\s#]*)(#[^)\s]*)?\)/g, (m, a, b, f = '') => (a === 'families' ? ']()' : `](/wiki/${a}/${b.replace(/\/$/, '')}${b ? '/' : ''}${f})`))
  .replace(/\[([^\]]*)\]\(\)/g, '$1');
for (const r of gddRows) { r.body_md = fixSiteLinks(fixGddRelative(r.body_md, r.source_path)); r.body_ko_md = fixSiteLinks(fixGddRelative(r.body_ko_md, r.source_path)); }
for (const r of wikiDocRows) { r.body_md = fixSiteLinks(fixWikiRoutes(r.body_md)); r.body_ko_md = fixSiteLinks(fixWikiRoutes(r.body_ko_md)); }

if (missing.size) {
  fs.writeFileSync(MISSING_PATH, JSON.stringify([...missing], null, 1));
  console.error(`E_I18N_MISSING: ${missing.size} Korean strings lack English; see ${path.relative(REPO, MISSING_PATH)}`);
  process.exit(2);
}
if (fs.existsSync(MISSING_PATH)) fs.rmSync(MISSING_PATH);

// ---- emit SQL -----------------------------------------------------------
const SCHEMA = `
CREATE TABLE site_meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE wiki_category (id TEXT PRIMARY KEY, parent_id TEXT, sort INTEGER NOT NULL, label TEXT NOT NULL, label_ko TEXT NOT NULL, summary TEXT NOT NULL, summary_ko TEXT NOT NULL);
CREATE TABLE wiki_document (slug TEXT PRIMARY KEY, title TEXT NOT NULL, title_ko TEXT NOT NULL, category_id TEXT NOT NULL REFERENCES wiki_category(id), sort INTEGER NOT NULL, body_md TEXT NOT NULL, body_ko_md TEXT NOT NULL);
CREATE TABLE faction (id TEXT PRIMARY KEY, sort INTEGER NOT NULL, name TEXT NOT NULL, name_ko TEXT NOT NULL, color TEXT NOT NULL, center_region TEXT NOT NULL, center_region_ko TEXT NOT NULL, ai_position TEXT NOT NULL, ai_position_ko TEXT NOT NULL);
CREATE TABLE wiki_state (slug TEXT PRIMARY KEY, id TEXT NOT NULL, sort INTEGER NOT NULL, faction_id TEXT NOT NULL REFERENCES faction(id), name TEXT NOT NULL, name_ko TEXT NOT NULL, government TEXT NOT NULL, government_ko TEXT NOT NULL, power TEXT NOT NULL, power_ko TEXT NOT NULL, cause TEXT NOT NULL, cause_ko TEXT NOT NULL, ruler TEXT NOT NULL, ruler_ko TEXT NOT NULL, capital TEXT NOT NULL, capital_ko TEXT NOT NULL, base TEXT NOT NULL, base_ko TEXT NOT NULL);
CREATE TABLE wiki_person (id TEXT PRIMARY KEY, sort INTEGER NOT NULL, faction_id TEXT NOT NULL REFERENCES faction(id), name TEXT NOT NULL, name_ko TEXT NOT NULL, title TEXT NOT NULL, title_ko TEXT NOT NULL, position TEXT NOT NULL, position_ko TEXT NOT NULL, rank TEXT NOT NULL, rank_ko TEXT NOT NULL, tier TEXT NOT NULL, occupation TEXT NOT NULL, occupation_ko TEXT NOT NULL, gender TEXT NOT NULL, gender_ko TEXT NOT NULL, stage TEXT NOT NULL, stage_ko TEXT NOT NULL, state_id TEXT NOT NULL, state_name TEXT NOT NULL, state_name_ko TEXT NOT NULL);
CREATE TABLE wiki_update (sort INTEGER PRIMARY KEY, date TEXT NOT NULL, category TEXT NOT NULL, category_ko TEXT NOT NULL, status TEXT NOT NULL, status_ko TEXT NOT NULL, title TEXT NOT NULL, title_ko TEXT NOT NULL, source TEXT NOT NULL, slug TEXT);
CREATE TABLE gdd_category (id TEXT PRIMARY KEY, sort INTEGER NOT NULL, label TEXT NOT NULL, label_ko TEXT NOT NULL);
CREATE TABLE gdd_document (id TEXT PRIMARY KEY, category_id TEXT NOT NULL REFERENCES gdd_category(id), slug TEXT NOT NULL, title TEXT NOT NULL, title_ko TEXT NOT NULL, summary TEXT NOT NULL, summary_ko TEXT NOT NULL, status TEXT NOT NULL, sort INTEGER NOT NULL, source_path TEXT, body_md TEXT NOT NULL, body_ko_md TEXT NOT NULL, UNIQUE (category_id, slug));
`.trim();
const cols = (s) => [...s.matchAll(/CREATE TABLE (\w+) \(([\s\S]*?)\);\s*$/gm)].reduce((a, m) => (a[m[1]] = m[2].split(/,\s*(?=\w+ (?:TEXT|INTEGER))/).map((c) => c.trim().split(' ')[0]), a), {});
const C = cols(SCHEMA);
writeSql('000-schema.sql', 'Schema (portable SQL: loads into SQLite and PostgreSQL). *_ko columns hold the Korean originals.', SCHEMA);
writeSql('010-meta.sql', 'Site metadata', insert('site_meta', ['key', 'value'], [
  { key: 'title', value: 'Seoul Metro Dynasties' }, { key: 'title_ko', value: '서울 지하철 왕조' }, { key: 'language', value: 'en' },
  { key: 'tagline', value: 'A grand-strategy and tabletop-CRPG world bible set in a post-blackout Seoul.' },
  { key: 'tagline_ko', value: '대정전 이후의 서울을 무대로 한 대전략·TRPG 기반 CRPG 세계관 위키.' },
  { key: 'schema', value: '2' },
]));
writeSql('020-wiki-categories.sql', 'Wiki categories', insert('wiki_category', C.wiki_category, wikiCategories));
writeSql('030-wiki-documents.sql', 'Wiki articles (Markdown bodies, English and Korean)', insert('wiki_document', C.wiki_document, wikiDocRows));
writeSql('035-factions.sql', 'Factions (owner decision 2026-11-10: Government, Free City, Arc; rename here only)', insert('faction', C.faction, factionRows));
writeSql('040-wiki-states.sql', 'States', insert('wiki_state', C.wiki_state, stateRows));
writeSql('050-wiki-people.sql', 'People roster', insert('wiki_person', C.wiki_person, personRows));
writeSql('060-wiki-updates.sql', 'Update history', insert('wiki_update', C.wiki_update, updateRows));
writeSql('070-gdd-categories.sql', 'GDD categories', insert('gdd_category', C.gdd_category, GDD_CATS.map(([id, label, label_ko], i) => ({ id, sort: i, label, label_ko }))));
writeSql('080-gdd-documents.sql', 'GDD documents (Markdown bodies, English and Korean)', insert('gdd_document', C.gdd_document, gddRows));
console.log(`exported: ${wikiDocRows.length} wiki docs, ${factionRows.length} factions, ${stateRows.length} states, ${personRows.length} people, ${updateRows.length} updates, ${gddRows.length} GDD docs (en+ko)`);
