#!/usr/bin/env node
// Exports the PUBLIC wiki + GDD projections into raw SQL files (data/sql/*.sql).
// Source of truth for GitHub Pages is data/sql; the site build never touches PostgreSQL.
//
//   PostgreSQL wiki --(npm run generate)--> src/generated/** --(this script)--> data/sql/*.sql
//
// Only public projections are read (never wiki_private, never .omo). Every Korean
// string must have an English entry in scripts/pages/i18n-ko-en.json; missing
// strings are written to scripts/pages/i18n-missing.json and the export fails.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const OUT = path.join(REPO, 'data/sql');
const CACHE_PATH = path.join(REPO, 'scripts/pages/i18n-ko-en.json');
const MISSING_PATH = path.join(REPO, 'scripts/pages/i18n-missing.json');
const HANGUL = /[\uAC00-\uD7A3]/;
const hasHangul = (s) => typeof s === 'string' && HANGUL.test(s);

const cache = fs.existsSync(CACHE_PATH) ? JSON.parse(fs.readFileSync(CACHE_PATH, 'utf8')) : {};
const missing = new Set();
const T = (s) => {
  if (!hasHangul(s)) return s;
  const v = cache[s];
  if (v === undefined) { missing.add(s); return s; }
  return v;
};
// Translate a markdown block line by line (cache keys are single lines).
const TL = (md) => md.split('\n').map(T).join('\n');

const gen = (p) => import(pathToFileURL(path.join(REPO, 'src/generated', p)).href);
const readJson = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));
const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
  const p = path.join(dir, e.name);
  return e.isDirectory() ? walk(p) : p.endsWith('.json') ? [p] : [];
}).sort();

// ---- SQL helpers --------------------------------------------------------
const q = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replaceAll("'", "''")}'`);
const insert = (table, cols, rows) => rows.map((r) => `INSERT INTO ${table} (${cols.join(', ')}) VALUES (${cols.map((c) => q(r[c])).join(', ')});`).join('\n');
const writeSql = (name, header, body) => {
  fs.mkdirSync(OUT, { recursive: true });
  fs.writeFileSync(path.join(OUT, name), `-- ${header}\n-- Generated by scripts/pages/export-sql.mjs. Raw data: edit via the export, not by hand.\n\n${body}\n`);
};

// ---- world documents (English projection) -------------------------------
function cleanWorldMarkdown(md) {
  const out = [];
  for (const line of md.split('\n')) {
    const a = line.match(/^<a id="([^"]*)"><\/a>\s*$/);
    if (a) { if (/^[\x20-\x7e]+$/.test(a[1])) out.push(line); continue; }
    out.push(line);
  }
  let text = out.join('\n');
  // Internal routes: /en/world/<Slug>[#frag] -> /wiki/<Slug>/[#frag]; Hangul fragments are dropped.
  text = text.replace(/\]\(\/(?:en\/)?world\/([A-Za-z0-9_-]*)(#[^)\s]*)?\)/g, (m, slug, frag = '') => {
    const f = frag && /^#[\x20-\x7e]+$/.test(frag) ? frag : '';
    return `](/wiki/${slug ? `${slug}/` : ''}${f})`;
  });
  // Links into the private design repository are not public; keep the label only.
  text = text.replace(/\[([^\]]+)\]\(https:\/\/github\.com\/islee23520\/seoul-dengoku\/[^)]*\)/g, '$1');
  // Remaining internal links: person routes / states, rewritten to site routes.
  text = text.replace(/\]\(\/en\/(states|people|families|updates|categories)(\/[^)\s#]*)?(#[^)\s]*)?\)/g, (m, a, b = '', f = '') => `](/wiki/${a}${b}/${/^#[\x20-\x7e]+$/.test(f) ? f : ''})`);
  // Fragments pointing at Hangul anchors inside external-looking links are not expected; strip any left.
  text = text.replace(/\]\(([^)\s]*)#[^)\s]*[\uAC00-\uD7A3][^)\s]*\)/g, ']($1)');
  return text;
}

const worldDir = path.join(REPO, 'src/generated/world-en');
const worldDocs = fs.readdirSync(worldDir).filter((f) => f.endsWith('.json')).sort().map((f) => {
  const j = readJson(path.join(worldDir, f));
  return { slug: j.slug, title: T(j.title), body: TL(cleanWorldMarkdown(j.reviewText)) };
});

// ---- categories ---------------------------------------------------------
const { categoryIndex } = await gen('categoryIndex.ts');
const wikiCategories = [];
const docCategory = new Map();
categoryIndex.categories.forEach((c, i) => {
  wikiCategories.push({ id: c.id, parent_id: null, sort: i, label: T(c.label), summary: T(c.summary) });
  c.documents.forEach((d, j) => { if (d.slug !== 'index' && !docCategory.has(d.slug)) docCategory.set(d.slug, { id: c.id, sort: j }); });
  c.children.forEach((ch, k) => wikiCategories.push({ id: ch.id, parent_id: c.id, sort: k, label: T(ch.label), summary: T(ch.summary ?? '') }));
});
wikiCategories.push({ id: 'other', parent_id: null, sort: 999, label: 'Other', summary: 'Pages not yet filed under a category.' });
const wikiDocRows = worldDocs.map((d, i) => {
  const cat = docCategory.get(d.slug) ?? { id: 'other', sort: i };
  return { slug: d.slug, title: d.title, category_id: cat.id, sort: cat.sort, body_md: d.body };
});

// ---- states / people / updates -----------------------------------------
const { stateCatalog } = await gen('stateCatalog.ts');
// The English articles already name every state in the Sixteen-States table; that spelling wins over machine translation.
const canonicalState = new Map();
for (const line of readJson(path.join(worldDir, 'Sixteen-States.json')).reviewText.split('\n')) {
  const m = line.match(/^\|\s*(S(?:0[1-9]|1[0-6]))\s*\|\s*([^|]+?)\s*\|/);
  if (m && !canonicalState.has(m[1])) canonicalState.set(m[1], m[2]);
}
if (canonicalState.size !== stateCatalog.length) throw new Error(`E_STATE_NAMES: ${canonicalState.size} canonical names for ${stateCatalog.length} states`);
const stateEn = (id, ko) => canonicalState.get(id) ?? T(ko);
const koHegemon = new Map(stateCatalog.map((s) => [s.name, stateEn(s.id, s.name)]));
const stateRows = stateCatalog.map((s, i) => ({
  slug: s.slug, id: s.id, sort: i, name: stateEn(s.id, s.name), government: T(s.government), power: T(s.power), cause: T(s.cause),
  ruler: T(s.ruler), capital: T(s.capital), hegemon: koHegemon.get(s.currentHegemon?.name) ?? T(s.currentHegemon?.name ?? ''), base: T(s.currentBase?.name ?? ''),
}));
const stateName = new Map(stateCatalog.map((s) => [s.id, stateEn(s.id, s.name)]));
const { peopleCatalog } = await gen('peopleCatalog.ts');
const personRows = peopleCatalog.map((p, i) => ({
  id: p.id, sort: i, name: T(p.name), title: T(p.title), position: T(p.position), rank: T(p.rank), tier: p.commonTier,
  occupation: T(p.occupation), gender: T(p.gender), stage: T(p.stage), state_id: p.state, state_name: stateName.get(p.state) ?? T(p.stateName),
}));
const { wikiUpdates } = await gen('wikiUpdates.ts');
const updateRows = wikiUpdates.map((u, i) => ({ sort: i, date: u.date, category: T(u.category), status: T(u.status), title: T(u.title), source: u.source, slug: (u.route.match(/^\/world\/([^/#]+)/) ?? [])[1] ?? null }));

// ---- GDD ----------------------------------------------------------------
const GDD_DIR = path.join(REPO, 'gdd/canon/locales/ko-KR');
const GDD_CATS = [
  ['design', 'Product Design', 'root'], ['rules', 'Game Rules', 'rules'], ['architecture', 'Architecture', 'architecture'],
  ['references', 'Reference Research', 'references'], ['decisions', 'Decision Records', 'adr'], ['art', 'Art Design', 'art'],
  ['system-design', 'System Design', 'system-design'], ['proposals', 'Design Proposals', 'proposals'],
];
const catOfFile = (rel) => {
  if (/^adr-\d+\.json$/.test(rel)) return 'decisions';
  const dir = rel.split('/')[0];
  return GDD_CATS.find((c) => c[2] === dir)?.[0] ?? 'design';
};
const files = walk(GDD_DIR).map((f) => ({ abs: f, rel: path.relative(GDD_DIR, f).replaceAll('\\', '/') }));
const gddMeta = files.map(({ abs, rel }) => {
  const j = readJson(abs);
  const id = j.document?.id ?? j.id;
  const slug = path.basename(rel, '.json');
  return { j, rel, id, slug, category: catOfFile(rel) };
});
const routeById = new Map(gddMeta.map((m) => [m.id, `/gdd/${m.category}/${m.slug}/`]));

const inl = (nodes) => (nodes ?? []).map((n) => {
  if (n.kind === 'docLink') { const r = routeById.get(n.targetDocumentId); const t = T(n.text); return r ? `[${t}](${r})` : t; }
  return T(n.text ?? '');
}).join('');
const cell = (c) => (Array.isArray(c) ? inl(c) : T(String(c))).replaceAll('|', '\\|').replaceAll('\n', ' ');
function blockMd(b) {
  switch (b.kind) {
    case 'heading': return `${'#'.repeat(b.level ?? b.depth ?? 2)} ${b.inlines ? inl(b.inlines) : T(b.text?.ko ?? '')}`;
    case 'paragraph': return b.inlines ? inl(b.inlines) : T(b.text?.ko ?? '');
    case 'list': return (b.items ?? []).map((it, i) => `${b.ordered ? `${i + 1}.` : '-'} ${Array.isArray(it) ? inl(it) : T(it.ko ?? '')}`).join('\n');
    case 'table': {
      const head = `| ${(b.header ?? []).map(cell).join(' | ')} |`;
      const sep = `| ${(b.header ?? []).map(() => '---').join(' | ')} |`;
      return [head, sep, ...(b.rows ?? []).map((r) => `| ${r.map(cell).join(' | ')} |`)].join('\n');
    }
    case 'blockQuote': return (b.lines ?? []).map((l) => `> ${Array.isArray(l) ? inl(l) : T(l)}`).join('\n');
    case 'codeFence': return `${b.fence ?? '```'}${b.info ?? ''}\n${T(b.text ?? '')}\n${b.fence ?? '```'}`;
    case 'thematicBreak': return '---';
    default: throw new Error(`E_GDD_BLOCK_KIND:${b.kind}`);
  }
}
const gddCats = GDD_CATS.map(([id, label], i) => ({ id, sort: i, label }));
const gddRows = gddMeta.map((m, i) => {
  const blocks = m.j.blocks ?? m.j.content;
  const body = blocks.map(blockMd).join('\n\n');
  const first = blocks.find((b) => b.kind === 'heading');
  const title = m.j.locales?.ko?.title ? T(m.j.locales.ko.title) : (first ? blockMd(first).replace(/^#+\s*/, '') : m.slug);
  const summary = m.j.locales?.ko?.summary ? T(m.j.locales.ko.summary) : '';
  return { id: m.id, category_id: m.category, slug: m.slug, title, summary, status: m.j.status ?? 'accepted', sort: i, source_path: m.j.source?.path ?? null, body_md: body };
});

// Relative Markdown links (foo.md, ../rules/Bar.md#frag) -> site routes by source path; unresolvable ones keep the label only.
const routeBySource = new Map(gddRows.map((r) => [r.source_path?.toLowerCase(), `/gdd/${r.category_id}/${r.slug}/`]));
const fixLinks = (row) => {
  const dir = path.posix.dirname(row.source_path ?? '.');
  row.body_md = row.body_md.replace(/\[([^\]]*)\]\(([^)\s#]+\.md)(#[^)\s]*)?\)/gi, (m, label, href) => {
    if (/^[a-z][a-z0-9+.-]*:/i.test(href) || href.startsWith('/')) return m;
    const target = routeBySource.get(path.posix.normalize(path.posix.join(dir, href)).toLowerCase());
    return target ? `[${label}](${target})` : label;
  });
};
gddRows.forEach(fixLinks);
wikiDocRows.forEach((r) => { r.body_md = r.body_md.replace(/\[([^\]]*)\]\((?![a-z][a-z0-9+.-]*:|\/|#)[^)\s]+\.md(?:#[^)\s]*)?\)/gi, '$1'); });

wikiDocRows.forEach((r) => { r.body_md = r.body_md.replace(/\]\(\/(people|states|families|updates)\/([^)\s#]*)(#[^)\s]*)?\)/g, (m, a, b, f = '') => (a === 'families' ? ']()' : `](/wiki/${a}/${b.replace(/\/$/, '')}${b ? '/' : ''}${f})`)).replace(/\[([^\]]*)\]\(\)/g, '$1'); });
const gddRouteSet = new Map(gddRows.map((r) => [`/gdd/${r.category_id}/${r.slug}/`.toLowerCase(), `/gdd/${r.category_id}/${r.slug}/`]));
const wikiRouteSet = new Map(wikiDocRows.map((r) => [`/wiki/${r.slug}/`.toLowerCase(), `/wiki/${r.slug}/`]));
const fixSiteLinks = (row) => {
  row.body_md = row.body_md.replace(/\]\((\/(?:gdd|wiki)\/[^)\s#]*?)\/?(#[^)\s]*)?\)/g, (m, p, frag = '') => {
    const key = `${p.replace('/wiki/world/', '/wiki/')}/`.toLowerCase();
    const hit = gddRouteSet.get(key) ?? wikiRouteSet.get(key);
    if (hit) return `](${hit}${frag})`;
    return /^\/wiki\/(states|people|updates)\//.test(p) || p === '/wiki' || p === '/gdd' ? m : ']()';
  });
  row.body_md = row.body_md.replace(/\[([^\]]*)\]\(\)/g, '$1');
};
gddRows.forEach(fixSiteLinks);
wikiDocRows.forEach(fixSiteLinks);

// ---- fail on untranslated Korean ---------------------------------------
if (missing.size) {
  fs.writeFileSync(MISSING_PATH, JSON.stringify([...missing], null, 1));
  console.error(`E_I18N_MISSING: ${missing.size} Korean strings lack English; see ${path.relative(REPO, MISSING_PATH)}`);
  process.exit(2);
}
if (fs.existsSync(MISSING_PATH)) fs.rmSync(MISSING_PATH);

// ---- emit SQL -----------------------------------------------------------
const SCHEMA = `
CREATE TABLE site_meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE wiki_category (id TEXT PRIMARY KEY, parent_id TEXT, sort INTEGER NOT NULL, label TEXT NOT NULL, summary TEXT NOT NULL);
CREATE TABLE wiki_document (slug TEXT PRIMARY KEY, title TEXT NOT NULL, category_id TEXT NOT NULL REFERENCES wiki_category(id), sort INTEGER NOT NULL, body_md TEXT NOT NULL);
CREATE TABLE wiki_state (slug TEXT PRIMARY KEY, id TEXT NOT NULL, sort INTEGER NOT NULL, name TEXT NOT NULL, government TEXT NOT NULL, power TEXT NOT NULL, cause TEXT NOT NULL, ruler TEXT NOT NULL, capital TEXT NOT NULL, hegemon TEXT NOT NULL, base TEXT NOT NULL);
CREATE TABLE wiki_person (id TEXT PRIMARY KEY, sort INTEGER NOT NULL, name TEXT NOT NULL, title TEXT NOT NULL, position TEXT NOT NULL, rank TEXT NOT NULL, tier TEXT NOT NULL, occupation TEXT NOT NULL, gender TEXT NOT NULL, stage TEXT NOT NULL, state_id TEXT NOT NULL, state_name TEXT NOT NULL);
CREATE TABLE wiki_update (sort INTEGER PRIMARY KEY, date TEXT NOT NULL, category TEXT NOT NULL, status TEXT NOT NULL, title TEXT NOT NULL, source TEXT NOT NULL, slug TEXT);
CREATE TABLE gdd_category (id TEXT PRIMARY KEY, sort INTEGER NOT NULL, label TEXT NOT NULL);
CREATE TABLE gdd_document (id TEXT PRIMARY KEY, category_id TEXT NOT NULL REFERENCES gdd_category(id), slug TEXT NOT NULL, title TEXT NOT NULL, summary TEXT NOT NULL, status TEXT NOT NULL, sort INTEGER NOT NULL, source_path TEXT, body_md TEXT NOT NULL, UNIQUE (category_id, slug));
`.trim();
writeSql('000-schema.sql', 'Schema (portable SQL: loads into SQLite and PostgreSQL)', SCHEMA);
writeSql('010-meta.sql', 'Site metadata', insert('site_meta', ['key', 'value'], [
  { key: 'title', value: 'Seoul Metro Dynasties' }, { key: 'language', value: 'en' },
  { key: 'tagline', value: 'A grand-strategy and tabletop-CRPG world bible set in a post-blackout Seoul.' },
  { key: 'schema', value: '1' },
]));
writeSql('020-wiki-categories.sql', 'Wiki categories', insert('wiki_category', ['id', 'parent_id', 'sort', 'label', 'summary'], wikiCategories));
writeSql('030-wiki-documents.sql', 'Wiki articles (Markdown bodies)', insert('wiki_document', ['slug', 'title', 'category_id', 'sort', 'body_md'], wikiDocRows));
writeSql('040-wiki-states.sql', 'States', insert('wiki_state', ['slug', 'id', 'sort', 'name', 'government', 'power', 'cause', 'ruler', 'capital', 'hegemon', 'base'], stateRows));
writeSql('050-wiki-people.sql', 'People roster', insert('wiki_person', ['id', 'sort', 'name', 'title', 'position', 'rank', 'tier', 'occupation', 'gender', 'stage', 'state_id', 'state_name'], personRows));
writeSql('060-wiki-updates.sql', 'Update history', insert('wiki_update', ['sort', 'date', 'category', 'status', 'title', 'source', 'slug'], updateRows));
writeSql('070-gdd-categories.sql', 'GDD categories', insert('gdd_category', ['id', 'sort', 'label'], gddCats));
writeSql('080-gdd-documents.sql', 'GDD documents (Markdown bodies)', insert('gdd_document', ['id', 'category_id', 'slug', 'title', 'summary', 'status', 'sort', 'source_path', 'body_md'], gddRows));
console.log(`exported: ${wikiDocRows.length} wiki docs, ${stateRows.length} states, ${personRows.length} people, ${updateRows.length} updates, ${gddRows.length} GDD docs`);
