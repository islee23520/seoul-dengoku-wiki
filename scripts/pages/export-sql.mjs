function cleanWorldMarkdown(md, ko) {
  const out = [];
  for (const line of md.split('\n')) {
    const a = line.match(/^<a id="([^"]*)"><\/a>\s*$/);
    if (a) { if (ko || /^[\x20-\x7e]+$/.test(a[1])) out.push(line); continue; }
    out.push(line);
  }
  let text = out.join('\n');
  const fragOk = (f) => (f && (ko || /^#[\x20-\x7e]+$/.test(f)) ? f : '');
  text = text.replace(/\]\(\/(?:en\/)?world\/([A-Za-z0-9_-]*)(#[^)\s]*)?\)/g, (m, slug, frag = '') => `](/wiki/${slug ? `${slug}/` : ''}${fragOk(frag)})`);
  text = text.replace(/\[([^\]]+)\]\(https:\/\/github\.com\/islee23520\/seoul-dengoku\/[^)]*\)/g, '$1');
  text = text.replace(/\]\(\/(?:en\/)?(states|people|families|updates|categories)(\/[^)\s#]*)?(#[^)\s]*)?\)/g, (m, a, b = '', f = '') => `](/wiki/${a}${b}/${fragOk(f)})`);
  if (!ko) text = text.replace(/\]\(([^)\s]*)#[^)\s]*[\uAC00-\uD7A3][^)\s]*\)/g, ']($1)');
  return text;
}

