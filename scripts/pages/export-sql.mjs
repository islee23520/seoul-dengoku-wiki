#!/usr/bin/env node
// Exports the PUBLIC wiki + GDD projections into raw SQL files (data/sql/*.sql), in English and Korean.
// Source of truth for GitHub Pages is data/sql; the site build never touches PostgreSQL.
//
//   PostgreSQL wiki --(npm run generate)--> src/generated/** --(this script)--> data/sql/*.sql
//
// Korean text is the original projection; English comes from the existing English articles and
// scripts/pages/i18n-ko-en.json. Only public projections are read (never wiki_private, never .omo).
// Every Korean string that needs English must have an entry in the cache; missing strings are
// written to scripts/pages/i18n-missing.json and the export fails.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const OUT = path.join(REPO, 'data/sql');
const CACHE_PATH = path.join(REPO, 'scripts/pages/i18n-ko-en.json');
const MISSING_PATH = path.join(REPO, 'scripts/pages/i18n-missing.json');
const HANGUL = /[\uAC00-\uD7A3]/;
const hasHangul = (s) => typeof s === 'string' && HANGUL.test(s);

const cache = fs.existsSync(CACHE_PATH) ? JSON.parse(fs.readFileSync(CACHE_PATH, 'utf8')) : {};
const missing = new Set();
const T = (s) => {
  if (!hasHangul(s)) return s;
  const v = cache[s];
  if (v === undefined) { missing.add(s); return s; }
  return v;
};
const TL = (md) => md.split('\n').map(T).join('\n');
const K = (s) => s;
const KL = (md) => md;

const gen = (p) => import(pathToFileURL(path.join(REPO, 'src/generated', p)).href);
const readJson = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));
const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
  const p = path.join(dir, e.name);
  return e.isDirectory() ? walk(p) : p.endsWith('.json') ? [p] : [];
}).sort();

const q = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replaceAll("'", "''")}'`);
const insert = (table, cols, rows) => rows.map((r) => `INSERT INTO ${table} (${cols.join(', ')}) VALUES (${cols.map((c) => q(r[c])).join(', ')});`).join('\n');
const writeSql = (name, header, body) => {
  fs.mkdirSync(OUT, { recursive: true });
  fs.writeFileSync(path.join(OUT, name), `-- ${header}\n-- Generated by scripts/pages/export-sql.mjs. Raw data: edit via the export, not by hand.\n\n${body}\n`);
};

