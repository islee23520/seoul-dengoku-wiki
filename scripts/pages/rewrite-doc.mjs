#!/usr/bin/env node
// 문서 재작성 파이프라인 — docs/drafts/<slug>.{ko,en}.md 초안으로 data/sql/030-wiki-documents.sql의
// 해당 행만 UPDATE 하고, 파일 전체를 export-sql.mjs가 만든 원래 형식(머리말 주석 2줄 + 빈 줄 +
// 행당 INSERT 1문, 작은따옴표 2배 이스케이프, 본문의 실제 줄바꿈, 원래 행 순서) 그대로 재직렬화한다.
// data/sql/*.sql이 단독 정본이며 폐기된 export-sql.mjs는 역동기화 경로가 아니다(docs/REWRITE-PIPELINE.md 참조).
//
// 사용법:
//   node scripts/pages/rewrite-doc.mjs [--dry-run] [--drafts <dir>] [--only slug,slug] [--sql-dir <dir>]
//                                      [--allow-single-language] [--allow-shrink]
//   node scripts/pages/rewrite-doc.mjs --roundtrip        # 무변경 재직렬화가 원본과 바이트 동일인지 검증
//   node scripts/pages/rewrite-doc.mjs --refresh-header   # 030 머리말 둘째 줄을 정본 안내로 1회 교체
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { DatabaseSync } from 'node:sqlite';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '../..');

export const DOC_FILE = '030-wiki-documents.sql';
export const SQL_LOAD_FILES = ['000-schema.sql', '020-wiki-categories.sql', DOC_FILE];
export const DOC_COLUMNS = ['slug', 'title', 'title_ko', 'category_id', 'sort', 'body_md', 'body_ko_md'];
export const OLD_HEADER_LINE = '-- Generated by scripts/pages/export-sql.mjs. Raw data: edit via the export, not by hand.';
export const NEW_HEADER_LINE = '-- Source of truth: edit via scripts/pages/rewrite-doc.mjs (data/sql is canonical; the archived export-sql.mjs is not a sync path).';

// 불변식별 종료 코드 — 각 실패 경로가 서로 다른 0이 아닌 코드로 끝나야 한다.
export const EXIT = {
  USAGE: 1, SLUG_OR_COUNT: 2, SINGLE_LANGUAGE: 3, ANCHOR_SET: 4, HEADING_COUNT: 5, SHRINK: 6,
  MODEL_MISSING: 7, BODY_INVALID: 8, ROUNDTRIP_MISMATCH: 10, NO_DRAFTS: 11, SQL_LOAD: 12,
};

// ---- 030 파싱/직렬화 ------------------------------------------------------
// 문자열 리터럴('' 이스케이프)과 '--' 행 주석을 정확히 지나 문장을 자르고 INSERT 문에서 행 순서(slug)만
// 뽑는다. 값 자체는 node:sqlite가 적재한 표에서 읽는다.
export function parseDocumentsFile(text) {
  const nl = text.indexOf('\n');
  const nl2 = text.indexOf('\n', nl + 1);
  if (nl < 0 || nl2 < 0 || !text.startsWith('--') || !text.startsWith('--', nl + 1)) {
    throw new Error('E_HEADER: 머리말 주석 2줄로 시작하지 않는다');
  }
  const headerLines = [text.slice(0, nl), text.slice(nl + 1, nl2)];
  const slugs = [];
  let stmt = '';
  let inStr = false;
  const push = () => {
    let t = stmt;
    for (;;) { // 문두 주석 행/공백 제거(파일 머리말이 첫 INSERT 앞에 붙어 있다)
      const s = t.replace(/^\s+/, '');
      if (!s.startsWith('--')) { t = s; break; }
      const e = s.indexOf('\n');
      t = e < 0 ? '' : s.slice(e + 1);
    }
    stmt = '';
    if (!t.startsWith('INSERT INTO wiki_document')) return;
    const head = /^INSERT INTO wiki_document \(([^)]*)\) VALUES \(/.exec(t);
    if (!head || head[1].split(',').map((c) => c.trim()).join(',') !== DOC_COLUMNS.join(',')) {
      throw new Error(`E_INSERT_SHAPE: 예상 밖의 INSERT 형식: ${t.slice(0, 90)}`);
    }
    let i = head[0].length;
    while (i < t.length && (t[i] === ' ' || t[i] === '\n' || t[i] === '\t' || t[i] === '\r')) i++;
    if (t[i] !== "'") throw new Error(`E_SLUG_LITERAL: ${t.slice(0, 90)}`);
    i++;
    let slug = '';
    while (i < t.length) {
      if (t[i] === "'") {
        if (t[i + 1] === "'") { slug += "'"; i += 2; continue; }
        i++; break;
      }
      slug += t[i]; i++;
    }
    slugs.push(slug);
  };
  for (let i = 0; i < text.length;) {
    const c = text[i];
    if (inStr) {
      stmt += c;
      if (c === "'") {
        if (text[i + 1] === "'") { stmt += "'"; i += 2; continue; }
        inStr = false;
      }
      i++; continue;
    }
    if (c === "'") { inStr = true; stmt += c; i++; continue; }
    if (c === '-' && text[i + 1] === '-') {
      let j = i;
      while (j < text.length && text[j] !== '\n') j++;
      stmt += text.slice(i, j);
      i = j; continue;
    }
    if (c === ';') { push(); i++; continue; }
    stmt += c; i++;
  }
  push(); // 마지막 미완 결(주석만 남는다)
  if (new Set(slugs).size !== slugs.length) throw new Error('E_DUP_SLUG');
  return { headerLines, slugs };
}

// export-sql.mjs의 q()/insert()와 같은 형식으로 재직렬화한다.
const sqlValue = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replaceAll("'", "''")}'`);
export function serializeDocumentsFile(headerLines, rows) {
  if (!Array.isArray(headerLines) || headerLines.length !== 2) throw new Error('E_HEADER');
  const body = rows
    .map((r) => `INSERT INTO wiki_document (${DOC_COLUMNS.join(', ')}) VALUES (${DOC_COLUMNS.map((c) => sqlValue(r[c])).join(', ')});`)
    .join('\n');
  return `${headerLines[0]}\n${headerLines[1]}\n\n${body}\n`;
}

export function loadDatabase(sqlDir) {
  const db = new DatabaseSync(':memory:');
  for (const f of SQL_LOAD_FILES) {
    const p = path.join(sqlDir, f);
    if (!fs.existsSync(p)) throw new Error(`E_SQL_FILE: ${f}이(가) 없다 (${sqlDir})`);
    try { db.exec(fs.readFileSync(p, 'utf8')); } catch (e) { throw new Error(`E_SQL_EXEC: ${f}: ${e.message}`); }
  }
  return db;
}

// ---- 초안 -----------------------------------------------------------------
const DRAFT_RE = /^(.+)\.(ko|en)\.md$/;
function discoverDrafts(dir) {
  const found = new Map();
  if (!fs.existsSync(dir)) return { found, dirExists: false };
  for (const name of fs.readdirSync(dir).sort()) {
    const m = DRAFT_RE.exec(name);
    if (!m) continue; // <slug>.ko.md.part-<n> 조각은 무시 — 파이프라인은 최종 파일만 소비한다
    if (!found.has(m[1])) found.set(m[1], {});
    found.get(m[1])[m[2]] = path.join(dir, name);
  }
  return { found, dirExists: true };
}

// front matter는 두 '---' 행 사이. 본문은 닫는 '---' 행의 줄바꿈 다음부터 파일 끝까지가 그대로 본문 값이 된다.
export function parseDraft(file, text) {
  const lines = text.split('\n');
  if (lines[0].trim() !== '---') throw new Error(`E_FRONT_MATTER(${file}): '---' 줄로 시작해야 한다`);
  let end = -1;
  for (let i = 1; i < lines.length; i++) if (lines[i].trim() === '---') { end = i; break; }
  if (end < 0) throw new Error(`E_FRONT_MATTER(${file}): 닫는 '---' 줄이 없다`);
  const fm = {};
  for (let i = 1; i < end; i++) {
    const m = /^([A-Za-z_]+):\s?(.*)$/.exec(lines[i]);
    if (m) fm[m[1]] = m[2].trim();
  }
  const bodyOffset = lines.slice(0, end + 1).join('\n').length + 1;
  return { fm, body: text.slice(bodyOffset) };
}

const anchorSet = (body) => {
  const s = new Set();
  for (const m of body.matchAll(/<a\s+id=(["'])(.*?)\1\s*>\s*<\/a>/g)) s.add(m[2]);
  return s;
};
const headingCount = (body) => body.split('\n').reduce((n, l) => (l.startsWith('#') ? n + 1 : n), 0);
// HTML 주석 순서 검사(상태 스캔): 열지 않은 상태의 닫는 `-->`, 열린 상태의 중첩 여는 `<!--`,
// 끝까지 닫히지 않은 주석 모두 불균형으로 본다. 빈 주석 `<!---->`은 여·닫 순서가 맞으므로 균형이다.
const commentsBalanced = (body) => {
  let open = false;
  let i = 0;
  while (i < body.length) {
    const o = body.indexOf('<!--', i);
    const c = body.indexOf('-->', i);
    if (open) {
      if (c < 0) return false;             // 여린 채 EOF
      if (o >= 0 && o < c) return false;   // 중첩 여는 주석
      i = c + 3; open = false;
    } else {
      if (c >= 0 && (o < 0 || c < o)) return false; // 열지 않은 닫기
      if (o < 0) return true;
      i = o + 4; open = true;
    }
  }
  return !open;
};
const byteLen = (s) => Buffer.byteLength(s, 'utf8');
const setDiff = (a, b) => [...a].filter((x) => !b.has(x));
const pct = (n, o) => (o > 0 ? Math.round((n / o) * 100) : 100);

// ---- CLI ------------------------------------------------------------------
function usage() {
  console.error('사용법: node scripts/pages/rewrite-doc.mjs [--dry-run] [--drafts <dir>] [--only slug,slug] [--sql-dir <dir>] [--allow-single-language] [--allow-shrink]');
  console.error('        node scripts/pages/rewrite-doc.mjs --roundtrip | --refresh-header');
}

function parseArgs(argv) {
  const a = { dryRun: false, allowSingleLanguage: false, allowShrink: false, roundtrip: false, refreshHeader: false };
  const val = (i, name) => {
    const v = argv[i + 1];
    if (v === undefined || v.startsWith('--')) { console.error(`E_ARG: ${name} 값이 없다`); usage(); process.exit(EXIT.USAGE); }
    return v;
  };
  for (let i = 0; i < argv.length; i++) {
    const t = argv[i];
    if (t === '--dry-run') a.dryRun = true;
    else if (t === '--allow-single-language') a.allowSingleLanguage = true;
    else if (t === '--allow-shrink') a.allowShrink = true;
    else if (t === '--roundtrip') a.roundtrip = true;
    else if (t === '--refresh-header') a.refreshHeader = true;
    else if (t === '--drafts') { a.drafts = val(i, '--drafts'); i++; }
    else if (t === '--only') { a.only = val(i, '--only'); i++; }
    else if (t === '--sql-dir') { a.sqlDir = val(i, '--sql-dir'); i++; }
    else { console.error(`E_ARG: 알 수 없는 인자: ${t}`); usage(); process.exit(EXIT.USAGE); }
  }
  return a;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.roundtrip && args.refreshHeader) { console.error('E_ARG: --roundtrip과 --refresh-header는 함께 쓸 수 없다'); process.exit(EXIT.USAGE); }
  const sqlDir = args.sqlDir ? path.resolve(args.sqlDir) : path.join(REPO, 'data/sql');
  const docPath = path.join(sqlDir, DOC_FILE);
  const diskBuf = fs.readFileSync(docPath);
  const text = diskBuf.toString('utf8');
  let parsed;
  try { parsed = parseDocumentsFile(text); } catch (e) { console.error(`E_PARSE: ${e.message} (${docPath})`); process.exit(EXIT.SQL_LOAD); }
  let db;
  try { db = loadDatabase(sqlDir); } catch (e) { console.error(e.message); process.exit(EXIT.SQL_LOAD); }
  const rowsBySlug = new Map(db.prepare('SELECT * FROM wiki_document').all().map((r) => [r.slug, r]));
  if (rowsBySlug.size !== parsed.slugs.length) {
    console.error(`E_ROW_COUNT: ${DOC_FILE} 파싱 ${parsed.slugs.length}행 != wiki_document ${rowsBySlug.size}행`);
    process.exit(EXIT.SLUG_OR_COUNT);
  }
  for (const s of parsed.slugs) {
    if (!rowsBySlug.has(s)) { console.error(`E_SLUG: ${DOC_FILE}에는 있으나 wiki_document에 없는 slug: ${s}`); process.exit(EXIT.SLUG_OR_COUNT); }
  }

  if (args.roundtrip) {
    const out = Buffer.from(serializeDocumentsFile(parsed.headerLines, parsed.slugs.map((s) => rowsBySlug.get(s))), 'utf8');
    if (out.equals(diskBuf)) {
      console.log(`roundtrip OK: ${docPath} — 무변경 재직렬화가 원본과 바이트 동일 (${diskBuf.length} bytes)`);
      process.exit(0);
    }
    let off = 0;
    while (off < Math.min(out.length, diskBuf.length) && out[off] === diskBuf[off]) off++;
    console.error(`E_ROUNDTRIP: ${docPath} — 첫 차이 @byte ${off} (원본 ${diskBuf.length}B, 재직렬화 ${out.length}B)`);
    console.error(`  원본: ${JSON.stringify(diskBuf.toString('utf8', off, off + 80))}`);
    console.error(`  출력: ${JSON.stringify(out.toString('utf8', off, off + 80))}`);
    process.exit(EXIT.ROUNDTRIP_MISMATCH);
  }

  if (args.refreshHeader) {
    if (parsed.headerLines[1] === NEW_HEADER_LINE) { console.log(`머리말이 이미 정본 안내다: ${docPath}`); process.exit(0); }
    if (parsed.headerLines[1] !== OLD_HEADER_LINE) { console.error(`E_HEADER: 예상 밖의 머리말 둘째 줄: ${parsed.headerLines[1]}`); process.exit(EXIT.USAGE); }
    const out = serializeDocumentsFile([parsed.headerLines[0], NEW_HEADER_LINE], parsed.slugs.map((s) => rowsBySlug.get(s)));
    if (out !== text.replace(OLD_HEADER_LINE, NEW_HEADER_LINE)) {
      console.error('E_REFRESH: 머리말 외 바이트가 달라진다 — 먼저 --roundtrip으로 직렬화 무손실을 확인하라');
      process.exit(EXIT.ROUNDTRIP_MISMATCH);
    }
    if (args.dryRun) { console.log(`[dry-run] 머리말 둘째 줄을 정본 안내로 교체할 것이다: ${docPath}`); process.exit(0); }
    fs.writeFileSync(docPath, out);
    console.log(`머리말 교체 완료(나머지 바이트 불변): ${docPath} (${byteLen(out)} bytes)`);
    process.exit(0);
  }

  // ---- 초안 수집·검증·UPDATE ----
  const draftsDir = args.drafts ? path.resolve(args.drafts) : path.join(REPO, 'docs/drafts');
  const { found, dirExists } = discoverDrafts(draftsDir);
  if (!dirExists) { console.error(`E_NO_DRAFTS: 초안 디렉터리가 없다: ${draftsDir}`); process.exit(EXIT.NO_DRAFTS); }
  let targets;
  if (args.only) {
    targets = args.only.split(',').map((s) => s.trim()).filter(Boolean);
    if (!targets.length) { console.error('E_ARG: --only 값이 비었다'); usage(); process.exit(EXIT.USAGE); }
    for (const s of targets) if (!found.has(s)) { console.error(`E_NO_DRAFTS: --only ${s}: 초안 파일이 없다 (${draftsDir}/${s}.{ko,en}.md)`); process.exit(EXIT.NO_DRAFTS); }
  } else {
    targets = [...found.keys()];
  }
  if (!targets.length) { console.error(`E_NO_DRAFTS: 처리할 초안이 없다 (${draftsDir})`); process.exit(EXIT.NO_DRAFTS); }
  const skipped = [...found.keys()].filter((s) => !targets.includes(s));
  if (skipped.length) console.log(`범위 밖 무시: ${skipped.join(', ')}`);

  const updates = [];
  for (const slug of targets) {
    const pair = found.get(slug);
    // (a) slug 존재
    const row = rowsBySlug.get(slug);
    if (!row) { console.error(`E_SLUG: wiki_document에 '${slug}' 행이 없다 (초안 ${JSON.stringify(pair)})`); process.exit(EXIT.SLUG_OR_COUNT); }
    // (b) 언어 쌍 — 한 언어만 있으면 기각
    const langs = ['ko', 'en'].filter((l) => pair[l]);
    if (langs.length < 2 && !args.allowSingleLanguage) {
      console.error(`E_SINGLE_LANGUAGE: ${slug}: ${langs[0] ?? '?'} 초안만 있다 — ko/en를 함께 제출하거나 --allow-single-language를 사용하라`);
      process.exit(EXIT.SINGLE_LANGUAGE);
    }
    const drafts = {};
    for (const l of langs) {
      let d;
      try { d = parseDraft(pair[l], fs.readFileSync(pair[l], 'utf8')); } catch (e) { console.error(e.message); process.exit(EXIT.USAGE); }
      // (f) model id
      if (!d.fm.model || !d.fm.model.trim()) { console.error(`E_MODEL: ${slug}: ${l} 초안 front matter에 빈 값 아닌 model: 이 필요하다 (${pair[l]})`); process.exit(EXIT.MODEL_MISSING); }
      // (g) 본문 무결성
      if (d.body.includes('\0')) { console.error(`E_BODY: ${slug}: ${l} 새 본문에 NUL 바이트가 있다`); process.exit(EXIT.BODY_INVALID); }
      if (!commentsBalanced(d.body)) { console.error(`E_BODY: ${slug}: ${l} 새 본문의 HTML 주석이 여·닫 순서를 지키지 않는다(열지 않은 닫기 -->, 중첩 <!--, 미종결)`); process.exit(EXIT.BODY_INVALID); }
      drafts[l] = d;
    }
    const newKo = drafts.ko ? drafts.ko.body : row.body_ko_md;
    const newEn = drafts.en ? drafts.en.body : row.body_md;
    // (c) 앵커 집합 — 한 언어만 제출됐으면 다른 언어의 현재 본문과 비교한다
    const aKo = anchorSet(newKo), aEn = anchorSet(newEn);
    const onlyKo = setDiff(aKo, aEn), onlyEn = setDiff(aEn, aKo);
    if (onlyKo.length || onlyEn.length) {
      console.error(`E_ANCHORS: ${slug}: ko/en 명시 앵커 id 집합이 다르다 — ko에만 [${onlyKo.join(', ')}], en에만 [${onlyEn.join(', ')}]`);
      process.exit(EXIT.ANCHOR_SET);
    }
    // (d) 마크다운 제목 수
    const hKo = headingCount(newKo), hEn = headingCount(newEn);
    if (hKo !== hEn) { console.error(`E_HEADINGS: ${slug}: 마크다운 제목(#) 수가 다르다 — ko ${hKo} vs en ${hEn}`); process.exit(EXIT.HEADING_COUNT); }
    // (e) 길이 하한(바이트) — --allow-shrink로만 완화
    if (!args.allowShrink) {
      for (const [l, nb, ob] of [['ko', newKo, row.body_ko_md], ['en', newEn, row.body_md]]) {
        if (byteLen(nb) * 2 < byteLen(ob)) {
          console.error(`E_SHRINK: ${slug}: ${l} 새 본문 ${byteLen(nb)}B가 교체 대상 ${byteLen(ob)}B의 50% 미만이다 (--allow-shrink로 완화)`);
          process.exit(EXIT.SHRINK);
        }
      }
    }
    updates.push({
      slug, old: row, newKo, newEn,
      title: drafts.en?.fm.title ?? drafts.ko?.fm.title ?? row.title,
      titleKo: drafts.ko?.fm.title_ko ?? drafts.en?.fm.title_ko ?? row.title_ko,
      hKo, hEn, anchors: aKo.size,
      models: langs.map((l) => `${l}=${drafts[l].fm.model}`).join(' '),
      checkpoint: drafts.ko?.fm.section_checkpoint ?? drafts.en?.fm.section_checkpoint ?? '',
    });
  }

  const upd = db.prepare('UPDATE wiki_document SET title = ?, title_ko = ?, body_md = ?, body_ko_md = ? WHERE slug = ?');
  for (const u of updates) upd.run(u.title, u.titleKo, u.newEn, u.newKo, u.slug);
  // (a) 행 수 불변 — UPDATE만 하므로 변하면 안 된다
  const countAfter = db.prepare('SELECT COUNT(*) AS c FROM wiki_document').get().c;
  if (countAfter !== rowsBySlug.size) { console.error(`E_ROW_COUNT: 갱신 후 행 수 ${countAfter} != ${rowsBySlug.size}`); process.exit(EXIT.SLUG_OR_COUNT); }

  const refreshed = new Map(db.prepare('SELECT * FROM wiki_document').all().map((r) => [r.slug, r]));
  const rowsOut = parsed.slugs.map((s) => refreshed.get(s));
  // 실제 변경을 쓸 때만 머리말 둘째 줄을 정본 안내로 바꾼다(이미 바뀌어 있으면 그대로).
  const headerReplaced = !args.dryRun && parsed.headerLines[1] === OLD_HEADER_LINE;
  const headerLines = headerReplaced ? [parsed.headerLines[0], NEW_HEADER_LINE] : parsed.headerLines;
  const out = serializeDocumentsFile(headerLines, rowsOut);

  for (const u of updates) {
    const bits = [
      `${u.slug}:`, `model ${u.models};`,
      `ko ${byteLen(u.old.body_ko_md)}→${byteLen(u.newKo)}B(${pct(byteLen(u.newKo), byteLen(u.old.body_ko_md))}%),`,
      `en ${byteLen(u.old.body_md)}→${byteLen(u.newEn)}B(${pct(byteLen(u.newEn), byteLen(u.old.body_md))}%);`,
      `headings ${u.hKo}=${u.hEn};`, `anchors ${u.anchors}`,
    ];
    if (u.title !== u.old.title || u.titleKo !== u.old.title_ko) bits.push(`; title '${u.old.title}'→'${u.title}' / '${u.old.title_ko}'→'${u.titleKo}'`);
    if (u.checkpoint) bits.push(`; checkpoint ${u.checkpoint}`);
    console.log(bits.join(' '));
  }
  if (args.dryRun) { console.log(`[dry-run] 기록하지 않았다 — 반영 예정 ${updates.length}문서, 대상 ${docPath}`); process.exit(0); }
  fs.writeFileSync(docPath, out);
  console.log(`기록: ${docPath} (${byteLen(out)} bytes, ${updates.length}문서 반영${headerReplaced ? ', 머리말을 정본 안내로 교체' : ''})`);
  process.exit(0);
}

